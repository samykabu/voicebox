def test_no_temp_file_is_left_after_a_successful_save(tmp_path: Path) -> None:
    path = tmp_path / "nested" / "dir" / "out.wav"

    audio_mod.save_audio(_signal(), str(path), 24000)

    assert path.exists()
    assert not Path(f"{path}.tmp").exists()
    assert sorted(p.name for p in path.parent.iterdir()) == ["out.wav"]


def test_overwrite_replaces_the_file_atomically(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / "out.wav"
    path.write_bytes(b"old")
    replaced: list[tuple[str, str]] = []
    real_replace = os.replace

    def spy_replace(src, dst):
        replaced.append((str(src), str(dst)))
        return real_replace(src, dst)

    monkeypatch.setattr(os, "replace", spy_replace)

    audio_mod.save_audio(_signal(), str(path), 24000)

    assert replaced == [(f"{path}.tmp", str(path))]
    assert _info_tags(path.read_bytes()).get("ICMT") == DISCLOSURE


def test_failed_rename_cleans_up_and_keeps_the_old_file(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    path = tmp_path / "out.wav"
    path.write_bytes(b"old")

    def failing_replace(*_a, **_k):
        raise PermissionError("locked")

    monkeypatch.setattr(os, "replace", failing_replace)

    with pytest.raises(OSError, match="Failed to save audio"):
        audio_mod.save_audio(_signal(), str(path), 24000)

    assert path.read_bytes() == b"old"
    assert not Path(f"{path}.tmp").exists()


def test_failed_encode_cleans_up_and_creates_nothing(tmp_path: Path) -> None:
    path = tmp_path / "out.wav"

    with pytest.raises(OSError, match="Failed to save audio"):
        audio_mod.save_audio(_signal(), str(path), 0)  # an invalid rate makes libsndfile refuse

    assert not path.exists()
    assert not Path(f"{path}.tmp").exists()
