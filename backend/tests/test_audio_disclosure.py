@pytest.mark.parametrize("sample_rate", [24000, 48000])
@pytest.mark.parametrize("channels", [1, 2])
@pytest.mark.parametrize("dtype", [np.float32, np.float64])
def test_data_chunk_is_byte_identical_to_the_pre_t051_write(tmp_path: Path, sample_rate, channels, dtype) -> None:
    audio = _signal(channels).astype(dtype)
    tagged = tmp_path / "tagged.wav"
    reference = tmp_path / "reference.wav"

    audio_mod.save_audio(audio, str(tagged), sample_rate)
    _pre_t051_write(audio, reference, sample_rate)

    tagged_chunks = _riff_chunks(tagged.read_bytes())
    reference_chunks = _riff_chunks(reference.read_bytes())
    assert tagged_chunks[b"data"] == reference_chunks[b"data"]
    assert tagged_chunks[b"fmt "] == reference_chunks[b"fmt "]


def test_samples_rate_and_subtype_read_back_unchanged(tmp_path: Path) -> None:
    audio = _signal()
    tagged = tmp_path / "tagged.wav"
    reference = tmp_path / "reference.wav"

    audio_mod.save_audio(audio, str(tagged), 48000)
    _pre_t051_write(audio, reference, 48000)

    got, got_sr = sf.read(str(tagged), dtype="int16")
    want, want_sr = sf.read(str(reference), dtype="int16")
    assert got_sr == want_sr == 48000
    np.testing.assert_array_equal(got, want)
    assert sf.info(str(tagged)).subtype == sf.info(str(reference)).subtype == "PCM_16"
    assert sf.info(str(tagged)).frames == len(audio)


