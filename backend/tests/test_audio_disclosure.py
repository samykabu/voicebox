"""Every WAV saved by ``utils.audio.save_audio`` carries an AI-generated disclosure (T051, FR-026).

The disclosure is written into the WAV's RIFF ``LIST/INFO`` chunk through libsndfile
(``ICMT`` comment, ``ISFT`` software). It is read back two ways: through soundfile and by
walking the raw RIFF chunks. The audio itself must not change: the ``data`` chunk is
compared byte for byte with what the pre-T051 code path (``sf.write(..., format="WAV")``)
writes, and the atomic temp-file write and its cleanup behave as before.
"""

import os
import struct
from pathlib import Path

import numpy as np
import pytest
import soundfile as sf

from backend.utils import audio as audio_mod

DISCLOSURE = "AI-generated by Voicebox"


def _riff_chunks(raw: bytes) -> dict[bytes, bytes]:
    """Top-level chunks of a RIFF/WAVE file, by id (the last one wins)."""
    assert raw[:4] == b"RIFF", raw[:12]
    assert raw[8:12] == b"WAVE", raw[:12]
    chunks: dict[bytes, bytes] = {}
    pos = 12
    while pos + 8 <= len(raw):
        cid = raw[pos : pos + 4]
        (size,) = struct.unpack("<I", raw[pos + 4 : pos + 8])
        chunks[cid] = raw[pos + 8 : pos + 8 + size]
        pos += 8 + size + (size & 1)
    return chunks


def _info_tags(raw: bytes) -> dict[str, str]:
    """Sub-chunks of the LIST/INFO chunk, decoded and stripped of NUL padding."""
    chunks = _riff_chunks(raw)
    listing = chunks.get(b"LIST")
    if listing is None or listing[:4] != b"INFO":
        return {}
    tags: dict[str, str] = {}
    pos = 4
    while pos + 8 <= len(listing):
        tid = listing[pos : pos + 4].decode("ascii")
        (size,) = struct.unpack("<I", listing[pos + 4 : pos + 8])
        tags[tid] = listing[pos + 8 : pos + 8 + size].rstrip(b"\x00").decode("utf-8")
        pos += 8 + size + (size & 1)
    return tags


def _signal(channels: int = 1, n: int = 4801) -> np.ndarray:
    rng = np.random.default_rng(1234)
    data = (0.4 * rng.standard_normal((n, channels))).clip(-1, 1).astype(np.float32)
    return data[:, 0] if channels == 1 else data


def _pre_t051_write(audio: np.ndarray, path: Path, sample_rate: int) -> None:
    """What save_audio wrote before T051."""
    sf.write(str(path), audio, sample_rate, format="WAV")


