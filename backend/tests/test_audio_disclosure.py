def _tone_wav(path: Path, seconds: float = 3.0, sr: int = 24000, freq: float = 220.0) -> Path:
    t = np.linspace(0, seconds, int(sr * seconds), endpoint=False)
    sf.write(str(path), (0.3 * np.sin(2 * np.pi * freq * t)).astype(np.float32), sr)
    return path


